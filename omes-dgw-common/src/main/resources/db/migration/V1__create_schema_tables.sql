-- SQLite DDL for omes-dgw business tables (device / online / point-write)

-- Device category (single level)
CREATE TABLE T_DEVICE_CATEGORY (
    ID           TEXT         NOT NULL,
    NAME         TEXT         NOT NULL,
    CODE         TEXT         NOT NULL,
    CREATE_TIME  TEXT,
    UPDATE_TIME  TEXT,
    CREATE_BY    TEXT,
    UPDATE_BY    TEXT,
    DELETED      INTEGER      NOT NULL DEFAULT 0,
    PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX UK_DEVICE_CATEGORY_CODE ON T_DEVICE_CATEGORY (CODE);

-- Device
CREATE TABLE T_DEVICE (
    ID                   TEXT         NOT NULL,
    NAME                 TEXT         NOT NULL,
    CODE                 TEXT         NOT NULL,
    PROTOCOL             TEXT         NOT NULL,
    CATEGORY_CODE        TEXT,
    IP_ADDRESS           TEXT         NOT NULL,
    PORT                 INTEGER      NOT NULL,
    COLLECT_INTERVAL_SEC INTEGER      NOT NULL,
    CONNECT_TIMEOUT_MS   INTEGER      NOT NULL,
    ENABLED              INTEGER      NOT NULL DEFAULT 1,
    REMARK               TEXT,
    COLLECT_CONFIG       TEXT,
    CREATE_TIME          TEXT,
    UPDATE_TIME          TEXT,
    CREATE_BY            TEXT,
    UPDATE_BY            TEXT,
    DELETED              INTEGER      NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    FOREIGN KEY (CATEGORY_CODE) REFERENCES T_DEVICE_CATEGORY (CODE)
);

CREATE UNIQUE INDEX UK_DEVICE_CODE ON T_DEVICE (CODE);
CREATE INDEX IDX_DEVICE_CATEGORY_CODE ON T_DEVICE (CATEGORY_CODE);

-- Device online/offline periods
CREATE TABLE T_DEVICE_ONLINE_RECORD (
    ID           TEXT         NOT NULL,
    SN           TEXT         NOT NULL,
    START_TIME   TEXT         NOT NULL,
    END_TIME     TEXT,
    STATE        INTEGER      NOT NULL,
    EVENT_ID     TEXT         NOT NULL,
    CREATE_TIME  TEXT,
    UPDATE_TIME  TEXT,
    CREATE_BY    TEXT,
    UPDATE_BY    TEXT,
    DELETED      INTEGER      NOT NULL DEFAULT 0,
    PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX UK_DEVICE_ONLINE_RECORD_EVENT_ID ON T_DEVICE_ONLINE_RECORD (EVENT_ID);
CREATE INDEX IDX_DEVICE_ONLINE_RECORD_SN ON T_DEVICE_ONLINE_RECORD (SN);
CREATE INDEX IDX_DEVICE_ONLINE_RECORD_START ON T_DEVICE_ONLINE_RECORD (START_TIME);

-- Point write commands (TASK_ID groups commands; SEQ_NO orders within task)
CREATE TABLE T_DEVICE_POINT_WRITE_COMMAND (
    ID              TEXT         NOT NULL,
    TASK_ID         TEXT         NOT NULL,
    SEQ_NO          INTEGER      NOT NULL,
    DEVICE_ID       TEXT         NOT NULL,
    ADDRESS         TEXT         NOT NULL,
    DATA_TYPE       TEXT         NOT NULL,
    SCALE_FACTOR    REAL,
    BYTE_ORDER      TEXT,
    WRITE_VALUE     TEXT         NOT NULL,
    STATUS          TEXT         NOT NULL,
    ERROR_MESSAGE   TEXT,
    EXECUTED_TIME   TEXT,
    CREATE_TIME     TEXT,
    UPDATE_TIME     TEXT,
    CREATE_BY       TEXT,
    UPDATE_BY       TEXT,
    DELETED         INTEGER      NOT NULL DEFAULT 0,
    PRIMARY KEY (ID)
);

CREATE INDEX IDX_DEVICE_POINT_WRITE_CMD_TASK ON T_DEVICE_POINT_WRITE_COMMAND (TASK_ID, STATUS, SEQ_NO);
CREATE INDEX IDX_DEVICE_POINT_WRITE_CMD_STATUS ON T_DEVICE_POINT_WRITE_COMMAND (STATUS, CREATE_TIME, ID);
CREATE INDEX IDX_DEVICE_POINT_WRITE_CMD_DEVICE ON T_DEVICE_POINT_WRITE_COMMAND (DEVICE_ID);
